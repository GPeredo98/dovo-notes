-- Dovo Notes database schema.
-- Run once in a new Supabase project: Dashboard → SQL Editor → paste → Run.
-- Safe to re-run: every statement is idempotent.

-- ---------------------------------------------------------------------------
-- notes: one row per note
-- ---------------------------------------------------------------------------
create table if not exists public.notes (
  id           uuid primary key,                      -- generated by the client (crypto.randomUUID)
  user_id      uuid not null references auth.users (id) on delete cascade,
  title        text not null default 'Untitled note',
  content_html text not null default '',
  color        text not null default 'default'
               check (color in ('default', 'red', 'orange', 'yellow', 'green', 'blue', 'purple', 'pink')),
  pinned       boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()      -- set by the client, used for optimistic concurrency
);

create index if not exists notes_user_id_updated_at_idx on public.notes (user_id, updated_at desc);

alter table public.notes enable row level security;

drop policy if exists "Users can read their own notes" on public.notes;
create policy "Users can read their own notes"
  on public.notes for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own notes" on public.notes;
create policy "Users can create their own notes"
  on public.notes for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own notes" on public.notes;
create policy "Users can update their own notes"
  on public.notes for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own notes" on public.notes;
create policy "Users can delete their own notes"
  on public.notes for delete
  to authenticated
  using ((select auth.uid()) = user_id);

-- ---------------------------------------------------------------------------
-- profiles: per-user preferences (theme, recent tabs). Created lazily by upsert.
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id               uuid primary key references auth.users (id) on delete cascade,
  theme            text not null default 'dark' check (theme in ('dark', 'light')),
  recent_notes_ids uuid[] not null default '{}'
);

alter table public.profiles enable row level security;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "Users can create their own profile" on public.profiles;
create policy "Users can create their own profile"
  on public.profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

-- ---------------------------------------------------------------------------
-- Realtime: sync notes across devices
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notes'
  ) then
    alter publication supabase_realtime add table public.notes;
  end if;
end $$;
